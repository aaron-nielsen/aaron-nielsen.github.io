'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const ROOT=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(ROOT,'index.html'),'utf8');
const css=fs.readFileSync(path.join(ROOT,'clean-dashboard.css'),'utf8');
const original=path.join(ROOT,'assets','da-vinci-fantasy-lab-approved.webp');
const crest=path.join(ROOT,'assets','ram-hat-emblem.webp');
assert.ok(fs.existsSync(original),'Original user-approved Da Vinci illustration missing');
assert.ok(fs.existsSync(crest),'Supplied ram insignia missing');
assert.ok(fs.readFileSync(original).length>100000,'Original art should remain untouched');
const logo=fs.readFileSync(crest);
assert.equal(logo.toString('ascii',0,4),'RIFF');
assert.equal(logo.toString('ascii',8,12),'WEBP');
const bStart=html.indexOf('<div class="renaissance-banner">');
const bEnd=html.indexOf('<div class="league-switch">',bStart);
assert.ok(bStart>0&&bEnd>bStart,'Banner must precede league switch');
const banner=html.slice(bStart,bEnd);
assert.equal((html.match(/class="renaissance-banner"/g)||[]).length,1);
assert.doesNotMatch(banner,/<img\b/i,'Never add another HTML image: legacy full-width CSS stretched crest into a giant logo');
assert.match(banner,/class="renaissance-banner-art"/);
assert.match(banner,/viewBox="0 0 1500 240"/,'Must render a short panorama, not the old 3:1 banner');
assert.equal((banner.match(/href="\.\/assets\/da-vinci-fantasy-lab-approved\.webp"/g)||[]).length,3,
 'Recompose portrait, original wordmark and stats from approved art');
assert.match(banner,/<image href="\.\/assets\/ram-hat-emblem\.webp" x="120" y="30" width="38" height="38"/,
 'Ram insignia must be small and anchored on the hat');
assert.match(banner,/feColorMatrix/,'Emblem should blend in sepia and bronze');
const inline=html.slice(html.indexOf('<style id="compact-banner-styles">'));
assert.match(inline,/width:100vw!important/);
assert.match(inline,/height:clamp\(132px,14vw,200px\)!important/);
assert.match(inline,/height:102px!important/);
assert.match(inline,/height:86px!important/);
const styles=css.slice(css.indexOf('/* Compact, full-bleed parchment banner'));
assert.match(styles,/\.renaissance-banner>\.renaissance-banner-art/);
assert.doesNotMatch(styles,/\.hat-crest|\.renaissance-banner>img/);
const lastScript=html.lastIndexOf('<script>');
new Function(html.slice(lastScript+8,html.indexOf('</script>',lastScript)));
console.log('Short full-width original parchment banner, bronze ram badge and no giant HTML crest passed.');
