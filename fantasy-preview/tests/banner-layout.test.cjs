'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(ROOT,'index.html'),'utf8');
const css=fs.readFileSync(path.join(ROOT,'clean-dashboard.css'),'utf8');
const banner=path.join(ROOT,'assets','da-vinci-fantasy-lab-approved.webp');
const crest=path.join(ROOT,'assets','ram-hat-emblem.webp');
// Never replace Leonardo's existing, already approved artwork.
assert.ok(fs.existsSync(banner),'Original Da Vinci illustration missing');
assert.match(html,/class="renaissance-banner"><img src="\.\/assets\/da-vinci-fantasy-lab-approved\.webp"/);
assert.match(html,/class="hat-crest" src="\.\/assets\/ram-hat-emblem\.webp"/);
assert.equal((html.match(/class="renaissance-banner"/g)||[]).length,1);
const img=fs.readFileSync(crest);
assert.ok(img.length>=500);
assert.equal(img.toString('ascii',0,4),'RIFF');
assert.equal(img.toString('ascii',8,12),'WEBP');
const section=css.slice(css.lastIndexOf('/* October 2026: authentic Da Vinci parchment masthead.'));
assert.ok(section.length>1000,'Banner overrides missing');
assert.match(section,/width:100vw/);
assert.match(section,/max-width:none/);
assert.match(section,/height:clamp\(128px,12vw,166px\)/);
assert.match(section,/height:102px/);
assert.match(section,/height:90px/);
assert.match(section,/object-fit:cover/);
assert.match(section,/\.renaissance-banner \.hat-crest/);
assert.match(section,/sepia/);
console.log('Original artwork retained, full-bleed short parchment header and ram hat crest passed.');
