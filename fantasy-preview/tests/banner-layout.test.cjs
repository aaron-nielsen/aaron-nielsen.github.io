'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const styles=fs.readFileSync(path.join(base,'clean-dashboard.css'),'utf8');
const original=path.join(base,'assets/da-vinci-fantasy-lab-approved.webp');
assert.ok(fs.existsSync(original),'Original approved Da Vinci banner image must remain');
assert.ok(fs.statSync(original).size>100000,'Original source art should remain intact');
const start=html.indexOf('<div class="renaissance-banner">');
const end=html.indexOf('<div class="league-switch">',start);
assert.ok(start>=0&&end>start,'Banner must precede league controls');
const banner=html.slice(start,end);
assert.equal((html.match(/class="renaissance-banner"/g)||[]).length,1,'Only one masthead');
assert.doesNotMatch(banner,/<img\b/i,'No independent HTML crest that can grow to full-banner height');
assert.doesNotMatch(banner,/ram-hat-emblem/,'Optional ram insignia should be omitted until its placement is safe');
assert.match(banner,/class="renaissance-banner-art banner-desktop"/);
assert.match(banner,/class="renaissance-banner-art banner-mobile"/);
assert.match(banner,/viewBox="0 0 1500 200"/,'Full-width version must be shallow');
assert.match(banner,/viewBox="0 0 750 200"/,'Phone version must keep full title');
assert.equal((banner.match(/href="\.\/assets\/da-vinci-fantasy-lab-approved\.webp"/g)||[]).length,7,
 'All original source panels should render on wide and narrow screens');
assert.match(banner,/id="faceMask"/);
assert.match(banner,/id="titleMask"/);
assert.match(banner,/id="mSepia"/);
assert.match(banner,/id="inkSepia"/);
assert.match(banner,/feColorMatrix/,'Sepia color matrix should mute red');
const styStart=html.indexOf('<style id="compact-banner-styles">');
const styEnd=html.indexOf('</style>',styStart);
const inline=html.slice(styStart,styEnd);
assert.match(inline,/width:100vw!important/);
assert.match(inline,/height:clamp\(148px,13\.34vw,200px\)!important/);
assert.match(inline,/height:86px!important/);
assert.match(inline,/banner-desktop\{display:none!important\}/);
assert.match(inline,/banner-mobile\{display:block!important\}/);
assert.match(styles,/#page-overview\{width:100%;max-width:1020px/);
assert.match(styles,/grid-template-columns:minmax\(0,1fr\) 238px!important/);
const inlineStart=html.lastIndexOf('<script>');
const inlineEnd=html.indexOf('</script>',inlineStart);
new Function(html.slice(inlineStart+'<script>'.length,inlineEnd));
console.log('Compact original sepia banner, full title on phones and narrower Overview checks passed');
